// Note on `context`: the driver passes it through untouched so a board with several
// radios can tell them apart. This board has one radio, so every function ignores it
// and uses the LORA_* pins and hspi2 directly. Callers can pass NULL.

sx126x_hal_status_t sx126x_hal_reset( const void* context )
{
    ( void ) context;
    HAL_GPIO_WritePin(LORA_RST_GPIO_Port, LORA_RST_Pin, GPIO_PIN_RESET);
    HAL_Delay(1);
    HAL_GPIO_WritePin(LORA_RST_GPIO_Port, LORA_RST_Pin, GPIO_PIN_SET);
    HAL_Delay(0);
    return SX126X_HAL_STATUS_OK;
}

sx126x_hal_status_t sx126x_hal_wakeup( const void* context )
{
    ( void ) context;
    HAL_GPIO_WritePin(LORA_NSS_GPIO_Port, LORA_NSS_Pin, GPIO_PIN_RESET);
    HAL_Delay(1);
    HAL_GPIO_WritePin(LORA_NSS_GPIO_Port, LORA_NSS_Pin, GPIO_PIN_SET);
    return SX126X_HAL_STATUS_OK;  // TODO: return OK once implemented
}

sx126x_hal_status_t sx126x_hal_write( const void* context, const uint8_t* command, const uint16_t command_length,
                                      const uint8_t* data, const uint16_t data_length )
{
    ( void ) context;
    if (sx126x_hal_wait_on_busy() != SX126X_HAL_STATUS_OK)
    {
        return SX126X_HAL_STATUS_ERROR;
    }
    HAL_GPIO_WritePin(LORA_NSS_GPIO_Port, LORA_NSS_Pin, GPIO_PIN_RESET);
    HAL_StatusTypeDef status = HAL_SPI_Transmit(&hspi2, command, command_length, SX126X_HAL_SPI_TIMEOUT_MS);
    if (status == HAL_OK)
    {
        if (data_length > 0)
        {
            status = HAL_SPI_Transmit(&hspi2, data, data_length, SX126X_HAL_SPI_TIMEOUT_MS);
        }
    }
    HAL_GPIO_WritePin(LORA_NSS_GPIO_Port, LORA_NSS_Pin, GPIO_PIN_SET);
    return (status == HAL_OK) ? SX126X_HAL_STATUS_OK : SX126X_HAL_STATUS_ERROR;
}

