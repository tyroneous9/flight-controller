/*
 * -----------------------------------------------------------------------------
 * --- DEPENDENCIES ------------------------------------------------------------
 */

#include <stdint.h>
#include <stdbool.h>
#include <stddef.h>
#include <string.h>
#include "main.h"  // HAL types and the RADIO_* pin macros generated by CubeMX
#include "sx126x_hal.h"

/*
 * -----------------------------------------------------------------------------
 * --- PRIVATE MACROS ----------------------------------------------------------
 */

// How long to wait for BUSY to go low before giving up.
// Normal commands take microseconds; reset and wakeup take up to a few ms.
#define SX126X_HAL_BUSY_TIMEOUT_MS 100U

// Timeout passed to HAL_SPI_Transmit/Receive. At 1.3 MHz a 256-byte buffer takes ~2 ms.
#define SX126X_HAL_SPI_TIMEOUT_MS 10U

/*
 * -----------------------------------------------------------------------------
 * --- PRIVATE VARIABLES -------------------------------------------------------
 */

// Defined in main.c by CubeMX
extern SPI_HandleTypeDef hspi2;

/*
 * -----------------------------------------------------------------------------
 * --- PRIVATE FUNCTIONS DECLARATION -------------------------------------------
 */

/**
 * @brief Wait until radio busy pin returns to 0, or time out
 *
 * @returns SX126X_HAL_STATUS_OK when BUSY is low, SX126X_HAL_STATUS_ERROR on timeout
 */
static sx126x_hal_status_t sx126x_hal_wait_on_busy( void );

/*
 * -----------------------------------------------------------------------------
 * --- PUBLIC FUNCTIONS DEFINITION ---------------------------------------------
 */

// Note on `context`: the driver passes it through untouched so a board with several
// radios can tell them apart. This board has one radio, so every function ignores it
// and uses the RADIO_* pins and hspi2 directly. Callers can pass NULL.

sx126x_hal_status_t sx126x_hal_reset( const void* context )
{
    ( void ) context;
    HAL_GPIO_WritePin(RADIO_RST_GPIO_Port, RADIO_RST_Pin, GPIO_PIN_RESET);
    HAL_Delay(1);
    HAL_GPIO_WritePin(RADIO_RST_GPIO_Port, RADIO_RST_Pin, GPIO_PIN_SET);
    HAL_Delay(0);
    return SX126X_HAL_STATUS_OK;
}

sx126x_hal_status_t sx126x_hal_wakeup( const void* context )
{
    ( void ) context;
    HAL_GPIO_WritePin(RADIO_NSS_GPIO_Port, RADIO_NSS_Pin, GPIO_PIN_RESET);
    HAL_Delay(1);
    HAL_GPIO_WritePin(RADIO_NSS_GPIO_Port, RADIO_NSS_Pin, GPIO_PIN_SET);
    return SX126X_HAL_STATUS_OK;  // TODO: return OK once implemented
}

sx126x_hal_status_t sx126x_hal_write( const void* context, const uint8_t* command, const uint16_t command_length,
                                      const uint8_t* data, const uint16_t data_length )
{
    ( void ) context;
    if (sx126x_hal_wait_on_busy() != SX126X_HAL_STATUS_OK)
    {
        return SX126X_HAL_STATUS_ERROR;
    }
    HAL_GPIO_WritePin(RADIO_NSS_GPIO_Port, RADIO_NSS_Pin, GPIO_PIN_RESET);
    HAL_StatusTypeDef status = HAL_SPI_Transmit(&hspi2, command, command_length, SX126X_HAL_SPI_TIMEOUT_MS);
    if (status == HAL_OK)
    {
        if (data_length > 0)
        {
            status = HAL_SPI_Transmit(&hspi2, data, data_length, SX126X_HAL_SPI_TIMEOUT_MS);
        }
    }
    HAL_GPIO_WritePin(RADIO_NSS_GPIO_Port, RADIO_NSS_Pin, GPIO_PIN_SET);
    return (status == HAL_OK) ? SX126X_HAL_STATUS_OK : SX126X_HAL_STATUS_ERROR;
}

sx126x_hal_status_t sx126x_hal_read( const void* context, const uint8_t* command, const uint16_t command_length,
                                     uint8_t* data, const uint16_t data_length )
{
    ( void ) context;
    if(sx126x_hal_wait_on_busy() != SX126X_HAL_STATUS_OK)
    {
        return SX126X_HAL_STATUS_ERROR;
    }
    HAL_GPIO_WritePin(RADIO_NSS_GPIO_Port, RADIO_NSS_Pin, GPIO_PIN_RESET);
    HAL_StatusTypeDef status = HAL_SPI_Transmit(&hspi2, command, command_length, SX126X_HAL_SPI_TIMEOUT_MS);
    if(status == HAL_OK)
    {
        memset(data, 0, data_length);
        status = HAL_SPI_Receive(&hspi2, data, data_length, SX126X_HAL_SPI_TIMEOUT_MS);
    }
    HAL_GPIO_WritePin(RADIO_NSS_GPIO_Port, RADIO_NSS_Pin, GPIO_PIN_SET);
    return (status == HAL_OK) ? SX126X_HAL_STATUS_OK : SX126X_HAL_STATUS_ERROR;
}

/*
 * -----------------------------------------------------------------------------
 * --- PRIVATE FUNCTIONS DEFINITION --------------------------------------------
 */

static sx126x_hal_status_t sx126x_hal_wait_on_busy( void )
{
    uint32_t start_time = HAL_GetTick();
    while (HAL_GPIO_ReadPin(RADIO_BUSY_GPIO_Port, RADIO_BUSY_Pin) == GPIO_PIN_SET)
    {
        if(HAL_GetTick() - start_time > SX126X_HAL_BUSY_TIMEOUT_MS)
        {
            return SX126X_HAL_STATUS_ERROR;
        }
    }
    return SX126X_HAL_STATUS_OK;
}

